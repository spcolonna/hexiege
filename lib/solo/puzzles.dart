Stage _puzzle(
  String id,
  String title,
  String hint, {
  required Faction you,
  required List<Placed> pieces,
  int turns = 1,
  bool ability = false,
  int round = 6,
  Map<PieceType, int> hand = const {},
}) {
  final opp = you == Faction.shaolin ? Faction.ninja : Faction.shaolin;
  return Stage(
    id: id,
    kind: StageKind.puzzle,
    title: title,
    goal: turns == 1 ? 'Rodeá al Líder enemigo en 1 turno.' : 'Rodeá al Líder enemigo en $turns turnos.',
    intro: hint,
    you: you,
    opp: opp,
    level: AiLevel.hard,
    puzzleTurns: turns,
    build: () => buildScene(you: you, opp: opp, pieces: pieces, round: round, yourAbility: ability, yourHand: hand),
  );
}

