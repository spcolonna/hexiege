Stage _puzzle(
  String id, {
  required Faction you,
  required List<Placed> pieces,
  int turns = 1,
  bool ability = false,
  int round = 6,
  Map<PieceType, int> hand = const {},
}) {
  final opp = you == Faction.shaolin ? Faction.ninja : Faction.shaolin;
  return Stage(
    id: id,
    kind: StageKind.puzzle,
    you: you,
    opp: opp,
    level: AiLevel.hard,
    puzzleTurns: turns,
    build: () => buildScene(you: you, opp: opp, pieces: pieces, round: round, yourAbility: ability, yourHand: hand),
  );
}

